"""Rebuild netlify/functions/lib/site-knowledge.mjs from the public/*.html pages.
Run after changing page text:  python3 scripts/build-knowledge.py
The chat assistant answers only from this text, so keep it in sync with the site."""
import html, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = ["index", "builds", "services", "quote", "about", "warranty", "terms", "support", "privacy"]

def page_text(name):
    s = (ROOT / "public" / f"{name}.html").read_text()
    s = re.sub(r"(?is)<(script|style|noscript|svg|head)\b.*?</\1>", " ", s)
    s = re.sub(r"(?is)<(header|nav|footer)\b.*?</\1>", " ", s)  # site chrome repeats on every page
    s = re.sub(r"(?is)<form\b.*?</form>", " [quote request form] ", s)
    s = re.sub(r"(?i)<h([1-3])[^>]*>", lambda m: "\n\n" + "#" * int(m.group(1)) + " ", s)
    s = re.sub(r"(?i)</(p|li|tr|h[1-6]|div|section|table)>", "\n", s)
    s = re.sub(r"(?i)<(br|hr)\s*/?>", "\n", s)
    s = re.sub(r"(?i)</t[dh]>", " | ", s)
    s = re.sub(r"(?i)<li[^>]*>", "- ", s)
    s = re.sub(r"<[^>]+>", " ", s)
    s = html.unescape(s)
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r" *\n *", "\n", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()

parts = [f"=== PAGE: https://framefoundrypc.com/{n}.html ===\n{page_text(n)}" for n in PAGES]
text = "\n\n".join(parts)
out = ROOT / "netlify" / "functions" / "lib" / "site-knowledge.mjs"
out.write_text("// GENERATED by scripts/build-knowledge.py from public/*.html - do not edit by hand.\n"
               f"export const SITE_KNOWLEDGE = {json.dumps(text)};\n")
print(f"wrote {out.relative_to(ROOT)}: {len(text)} chars (~{len(text)//4} tokens)")
